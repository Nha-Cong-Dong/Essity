import { chromium } from "@playwright/test";
import fs from "node:fs";
const BASE="http://localhost:3100", OUT="../../.work/D1-SELFTEST-CORE/ev";
const [email, password] = fs.readFileSync("../../.work/D1-SELFTEST-CORE/account.txt","utf8").trim().split("\n");
const b = await chromium.launch();
const c = await b.newContext({viewport:{width:1440,height:900}});
const p = await c.newPage();
const logs=[]; p.on("console",m=>{if(m.type()==="error")logs.push(m.text().slice(0,160))}); p.on("response",r=>{if(r.status()>=400)logs.push(r.status()+" "+r.url())});
await p.goto(BASE+"/login"); await p.getByLabel(/email/i).fill(email); await p.getByLabel(/mật khẩu/i).first().fill(password); await p.keyboard.press("Enter");
await p.waitForURL(u=>!u.pathname.startsWith("/login"));
await p.goto(BASE+"/subjects"); await p.getByText("Xác suất thống kê").first().click(); await p.waitForLoadState("networkidle");
console.log("subject url", p.url());
const sid = p.url().split("/subjects/")[1].split(/[/?]/)[0];
fs.writeFileSync("../../.work/D1-SELFTEST-CORE/sid.txt", sid);
const links = await p.$$eval("a",as=>as.map(a=>a.getAttribute("href")+" | "+a.textContent.trim().slice(0,40)));
console.log(links.join("\n"));
await p.screenshot({path:`${OUT}/subject-d.png`,fullPage:true});
console.log(logs.join("\n"));
await b.close();
